/** 获取所有工具 */
export function getAllTools(): AITool[] {
  return [...tools].sort((a, b) => a.order - b.order);
}

/** 根据 ID 获取工具 */
export function getToolById(id: string): AITool | undefined {
  return tools.find((t) => t.id === id);
}

/** 根据分类 ID 获取工具列表 */
export function getToolsByCategory(categoryId: string): AITool[] {
  return tools
    .filter((t) => t.categoryId === categoryId)
    .sort((a, b) => a.order - b.order);
}

/** 获取精选工具 */
export function getFeaturedTools(): AITool[] {
  return tools
    .filter((t) => t.isFeatured)
    .sort((a, b) => a.order - b.order);
}

/** 获取热门工具 */
export function getPopularTools(): AITool[] {
  return tools
    .filter((t) => t.isPopular)
    .sort((a, b) => a.order - b.order);
}

/** 根据 ID 列表获取工具 */
export function getToolsByIds(ids: string[]): AITool[] {
  return ids
    .map((id) => tools.find((t) => t.id === id))
    .filter((t): t is AITool => t !== undefined)
    .sort((a, b) => a.order - b.order);
}

/** 获取相关工具（同分类的其他工具） */
export function getRelatedTools(toolId: string, limit = 4): AITool[] {
  const tool = getToolById(toolId);
  if (!tool) return [];
  return tools
    .filter((t) => t.categoryId === tool.categoryId && t.id !== toolId)
    .sort((a, b) => a.order - b.order)
    .slice(0, limit);
}
